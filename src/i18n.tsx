const DICTS: Record<Lang, Record<MessageKey, string>> = { en, mr };

// Latin digits keep amounts and dates easy to cross-check with the source documents.
const LOCALES: Record<Lang, string> = { en: 'en-IN', mr: 'mr-IN-u-nu-latn' };

let currentLocale = LOCALES.en;
/** Locale for date/number formatting outside React components. */
export const getLocale = () => currentLocale;

interface I18n {
    lang: Lang;
    setLang: (lang: Lang) => void;
    t: (key: MessageKey, vars?: Record<string, string | number>) => string;
}

const I18nContext = createContext<I18n | null>(null);
const STORAGE_KEY = 'evidence-viewer-lang';

export function I18nProvider({ children }: { children: ReactNode }) {
    const [lang, setLangState] = useState<Lang>(() => (localStorage.getItem(STORAGE_KEY) === 'mr' ? 'mr' : 'en'));
    currentLocale = LOCALES[lang];

    useEffect(() => {
        document.documentElement.lang = lang;
        document.title = DICTS[lang].appTitle;
        localStorage.setItem(STORAGE_KEY, lang);
    }, [lang]);

    const t = useCallback<I18n['t']>(
        (key, vars) => {
            let s = DICTS[lang][key] ?? en[key];
            if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
            return s;
        },
        [lang],
    );

    const value = useMemo(() => ({ lang, setLang: setLangState, t }), [lang, t]);
    return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18n {
    const ctx = useContext(I18nContext);
    if (!ctx) throw new Error('useI18n must be used inside I18nProvider');
    return ctx;
}
